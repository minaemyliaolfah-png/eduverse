import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {initializeTestEnvironment,assertFails} from '@firebase/rules-unit-testing';
import * as app from 'firebase/app';
import * as auth from 'firebase/auth';
import * as db from 'firebase/database';
import * as fs from 'firebase/firestore';
import {FirebaseClient} from '../js/firebase-client.js';
import {initialProgress,claimReward} from '../js/progress.js';

const sdk={app,auth,db,fs},projectId='demo-eduverse';
const config={apiKey:'demo-key',projectId,authDomain:'demo-eduverse.firebaseapp.com',databaseURL:'https://demo-eduverse.firebaseio.com',appId:'demo-eduverse'};
const waitUntil=async(fn,label)=>{const end=Date.now()+12000;while(Date.now()<end){if(await fn())return;await new Promise(r=>setTimeout(r,60));}throw Error(`Timeout: ${label}`);};
test('Firebase: two distinct accounts, sync, privacy, moderation, disconnect, reconnect', {timeout:120000}, async()=>{
 const env=await initializeTestEnvironment({projectId,database:{host:'127.0.0.1',port:9000,rules:await readFile('firebase/database.rules.json','utf8')},firestore:{host:'127.0.0.1',port:8080,rules:await readFile('firebase/firestore.rules','utf8')}});
 await env.clearDatabase();await env.clearFirestore();
 const clients=['a','b','c'].map(name=>new FirebaseClient(sdk,config,{name:`test-${name}-${Date.now()}`,emulator:true}));
 const [a,b,c]=clients;let roomA,roomB;
 try{
  await assertFails(db.get(db.ref(c.db,'rooms')));
  for(const [i,client] of clients.entries())await client.login(`test-${i}-${Date.now()}@example.test`,'Demo-only-12345',true);
  assert.notEqual(a.auth.currentUser.uid,b.auth.currentUser.uid);
  const pa={...initialProgress(),name:'Alya'},pb={...initialProgress(),name:'Bima'};
  pa.talked=pa.read=pa.passed=true;claimReward(pa);
  await a.saveProgress(pa);assert.equal((await a.readProgress()).xp,150);
  await assertFails(fs.getDoc(fs.doc(b.fs,'practiceProfiles',a.auth.currentUser.uid)));
  await assertFails(fs.getDocs(fs.collection(a.fs,'practiceProfiles')));
  await assertFails(fs.setDoc(fs.doc(a.fs,'practiceProfiles',a.auth.currentUser.uid),{version:1,progress:{...pa,xp:9999},updatedAt:fs.serverTimestamp()}));
  await assertFails(fs.setDoc(fs.doc(a.fs,'practiceProfiles',a.auth.currentUser.uid),{version:1,progress:pa,admin:true,updatedAt:fs.serverTimestamp()}));
  const code=await a.createRoom('Kelas Uji',pa);let seenA={},seenB={},messagesB={};
  const poseA={...pa,x:0,y:0,z:21,angle:0,area:'hub',moving:false},poseB={...pb,x:2,y:0,z:21,angle:0,area:'hub',moving:false};
  await assertFails(db.get(db.ref(b.db,`rooms/${code}/players`)));
  await assertFails(db.set(db.ref(b.db,`rooms/${code}/slots/24`),b.auth.currentUser.uid));
  await assertFails(db.set(db.ref(b.db,`rooms/${code}/members/${b.auth.currentUser.uid}`),{name:'Bima',joinedAt:db.serverTimestamp(),slot:'23'}));
  roomA=await a.join(code,pa,()=>poseA,{players:p=>seenA=p});
  await waitUntil(()=>roomA.ready,'A presence');
  roomB=await b.join(code,pb,()=>poseB,{players:p=>seenB=p,messages:m=>messagesB=m});
  await waitUntil(()=>roomB.ready&&seenA[b.auth.currentUser.uid]&&seenB[a.auth.currentUser.uid],'two distinct avatars');
  assert.equal(seenA[b.auth.currentUser.uid].name,'Bima');assert.equal(seenB[a.auth.currentUser.uid].name,'Alya');
  poseB.x=6;poseB.moving=true;
  await waitUntil(()=>seenA[b.auth.currentUser.uid]?.x===6,'position synchronization');
  roomB.gesture(2);await waitUntil(()=>seenA[b.auth.currentUser.uid]?.emote===2,'emote synchronization');
  await roomA.send(0);await waitUntil(()=>messagesB[a.auth.currentUser.uid]?.code===0,'quick chat');
  await assert.rejects(()=>roomA.send(1));
  await assertFails(db.set(db.ref(a.db,`rooms/${code}/messages/${a.auth.currentUser.uid}`),{name:'Alya',code:1,at:db.serverTimestamp()}));
  await assertFails(db.set(db.ref(b.db,`rooms/${code}/players/${a.auth.currentUser.uid}/attack`),{...poseB,at:db.serverTimestamp()}));
  await assertFails(db.get(db.ref(c.db,`rooms/${code}/players`)));
  await assertFails(db.get(db.ref(c.db,'rooms')));
  const raw=(await db.get(roomB.reference)).val();
  await assertFails(db.set(roomB.reference,{...raw,x:500,at:db.serverTimestamp()}));
  await assertFails(db.set(roomB.reference,{...raw,email:'private@example.test',at:db.serverTimestamp()}));
  await assertFails(db.set(db.ref(b.db,`rooms/${code}/meta/owner`),b.auth.currentUser.uid));
  await roomA.moderate(b.auth.currentUser.uid,'mute');
  await assertFails(db.set(db.ref(b.db,`rooms/${code}/messages/${b.auth.currentUser.uid}`),{name:'Bima',code:0,at:db.serverTimestamp()}));
  await roomA.moderate(b.auth.currentUser.uid,'unmute');await roomB.send(5);
  db.goOffline(b.db);
  await waitUntil(()=>!seenA[b.auth.currentUser.uid],'onDisconnect removes player');
  assert.equal((await db.get(db.ref(a.db,`rooms/${code}/players/${b.auth.currentUser.uid}`))).exists(),false);
  db.goOnline(b.db);await waitUntil(()=>roomB.ready&&seenA[b.auth.currentUser.uid],'reconnect restores player');
  await roomA.moderate(b.auth.currentUser.uid,'kick');await waitUntil(()=>roomB.closed&&!seenA[b.auth.currentUser.uid],'kick revokes presence');
  await assert.rejects(()=>b.join(code,pb,()=>poseB,{}));
  await roomA.moderate(b.auth.currentUser.uid,'unblock');
  roomB=await b.join(code,pb,()=>poseB,{players:p=>seenB=p});
  await waitUntil(()=>roomB.ready&&seenA[b.auth.currentUser.uid],'unblock allows rejoin');
  await roomA.closeRoom();await waitUntil(()=>roomA.closed,'close room');await assert.rejects(()=>c.join(code,pb,()=>poseB,{}));
  console.log('PASS: distinct auth UIDs, bidirectional positions, emote, chat, private progress, denied spoofing, rate limit, mute, kick, disconnect/reconnect, room closure.');
 }finally{for(const client of clients){await client.leave();await app.deleteApp(client.app);}await env.cleanup();}
});
